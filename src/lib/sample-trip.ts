function hydrateSampleStops(): Array<StopData & { id: string }> {
  const days = [1, 2, 3]
  const out: Array<StopData & { id: string }> = []
  for (const d of days) {
    const dayStops = RAW_STOPS.filter((s) => s.dayNumber === d)
    const schedule = computeDaySchedule(dayStops, d === 1 ? 6 * 60 + 30 : 8 * 60)
    for (const item of schedule.items) {
      out.push({
        ...item.stop,
        startTime: item.stop.fixedTime ? item.stop.startTime : item.startTime,
        travelMinutesFromPrev: item.travelMinutesFromPrev,
        travelDistanceKmFromPrev: item.travelDistanceKmFromPrev,
      })
    }
  }
  return out
}

